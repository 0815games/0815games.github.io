import { strict as assert } from 'node:assert';
import { createCoopInput } from '../coop-input.mjs';
const calls=[],resolvers=[];
const client={command(c){calls.push(c);return new Promise(resolve=>resolvers.push(resolve));}};
const input=createCoopInput(client);input.setEnabled(true);
void input.direction({type:'direction',x:1,y:0});
void input.direction({type:'direction',x:0,y:1});
void input.direction({type:'direction',x:0,y:0});
assert.equal(calls.length,1);
assert.equal((await input.execute({type:'build',pad:0,towerType:0})).ok,false);
resolvers.shift()({ok:true});await new Promise(resolve=>setTimeout(resolve,0));
assert.deepEqual(calls[1],{type:'direction',x:0,y:0},'last key release must be sent');
input.setEnabled(false);input.setEnabled(true);
void input.direction({type:'direction',x:-1,y:0});
resolvers.shift()({ok:true});await new Promise(resolve=>setTimeout(resolve,0));
assert.deepEqual(calls[2],{type:'direction',x:-1,y:0},'new input after reconnect must not get stuck');
resolvers.shift()({ok:true});await new Promise(resolve=>setTimeout(resolve,0));
input.setEnabled(false);assert.equal((await input.execute({type:'startWave'})).ok,false);
console.log('Co-op input serialization and movement release tests passed.');
