"use strict";
const assert=require("node:assert/strict");
const {toWorld,placementError}=require("../game/js/build-menu-art.js");
let passed=0;function test(name,run){run();passed++;console.log("OK "+name);}
const rect={left:100,top:50,width:940,height:600};
const camera={x:470,y:300,w:940,h:600,z:1};
const state=()=>({enabled:true,cost:100,gold:150,width:940,height:600,ground:[[100,100],[300,100]],towers:[]});
const good={x:500,y:300};
test("Kartenmitte",()=>assert.deepEqual(toWorld(570,350,rect,camera),{x:470,y:300}));
test("Zoom und Verschiebung",()=>assert.deepEqual(toWorld(670,350,rect,{...camera,x:600,z:2}),{x:650,y:300}));
test("CSS-Skalierung",()=>assert.deepEqual(toWorld(335,200,{...rect,width:470,height:300},camera),{x:470,y:300}));
test("Außerhalb links",()=>assert.equal(toWorld(99,350,rect,camera),null));
test("Außerhalb unten",()=>assert.equal(toWorld(570,651,rect,camera),null));
test("Nullbreite",()=>assert.equal(toWorld(570,350,{...rect,width:0},camera),null));
test("Ungültiger Zoom",()=>assert.equal(toWorld(570,350,rect,{...camera,z:0}),null));
test("NaN",()=>assert.equal(toWorld(NaN,350,rect,camera),null));
test("Gültiger Bauplatz",()=>assert.equal(placementError(good,state()),""));
test("Exakt ausreichend Gold",()=>assert.equal(placementError(good,{...state(),gold:100}),""));
test("Zu wenig Gold",()=>assert.equal(placementError(good,{...state(),gold:99}),"Nicht genug Gold."));
test("Rabattierter Preis",()=>assert.equal(placementError(good,{...state(),cost:95,gold:95}),""));
test("Bausperre",()=>assert.equal(placementError(good,{...state(),enabled:false}),"Bauen ist gerade gesperrt."));
test("Drop außerhalb",()=>assert.equal(placementError(null,state()),"Außerhalb der Karte."));
test("Kartenrand überschritten",()=>assert.equal(placementError({x:941,y:300},state()),"Außerhalb der Karte."));
test("Bodenweg",()=>assert.equal(placementError({x:200,y:100},state()),"Zu nah am Bodenweg."));
test("Wegabstand",()=>assert.equal(placementError({x:200,y:125},state()),"Zu nah am Bodenweg."));
test("Außerhalb Wegabstand",()=>assert.equal(placementError({x:200,y:127},state()),""));
test("Besetzter Platz",()=>assert.equal(placementError(good,{...state(),towers:[{x:510,y:300}]}),"Bauplatz ist bereits belegt."));
test("Freier Abstand",()=>assert.equal(placementError(good,{...state(),towers:[{x:550,y:300}]}),""));
test("Keine Mutation",()=>{const s=state(),before=JSON.stringify(s);placementError(good,s);assert.equal(JSON.stringify(s),before);});
console.log("Turm-Drag: "+passed+" Prüfungen bestanden.");
