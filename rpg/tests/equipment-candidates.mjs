import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../js/systems/equipment-candidates.js',import.meta.url),'utf8');
const {equipmentCandidates:find}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
let checks=0;const check=fn=>{fn();checks++;};
const slots=['head','body','mainhand','offhand','feet','ring'];
const items=Object.fromEntries(slots.map(slot=>[slot,{slot,name:slot}]));
items.potion={type:'potion',effect:'hp'};
const inventory=slots.map(id=>({id,count:1}));inventory.push({id:'potion',count:2});
for(const slot of slots)check(()=>{const found=find(inventory,slot,items);assert.equal(found.length,1);assert.equal(found[0].id,slot);assert.equal(found[0].entry,inventory[found[0].index]);});
check(()=>assert.deepEqual(find([], 'head',items),[]));
check(()=>assert.deepEqual(find(inventory,'unknown',items),[]));
check(()=>assert.deepEqual(find(null,'head',items),[]));
check(()=>assert.deepEqual(find(inventory,'head',null),[]));
check(()=>assert.deepEqual(find([null,{id:'missing',count:1},{id:'head',count:0},{id:'head',count:-1},{id:'head',count:1.5},{id:'head',count:'1'}],'head',items),[]));
check(()=>{const inherited=Object.create({head:{slot:'head'}});assert.deepEqual(find([{id:'head',count:1}],'head',inherited),[]);});
check(()=>{const before=JSON.stringify({inventory,items});find(inventory,'head',items);assert.equal(JSON.stringify({inventory,items}),before);});
check(()=>{const p=[{id:'head',count:2},{id:'head',count:1}];assert.deepEqual(find(p,'head',items).map(x=>[x.index,x.count]),[[0,2],[1,1]]);});
console.log(JSON.stringify({checks,passed:checks,scope:'Actual candidate filter with item/inventory fixtures; no UI or equip action test.'}));
